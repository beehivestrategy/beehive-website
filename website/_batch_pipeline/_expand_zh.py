def read(p): return open(p, encoding="utf-8").read()
def write(p, s): open(p, "w", encoding="utf-8").write(s)

report = []
for slug, (marker, block) in ZH.items():
    p = os.path.join(ROOT, "zh-cn/blog/articles", slug + ".html")
    if not os.path.exists(p):
        report.append(f"[MISSING] {slug}")
        continue
    html = read(p)
    if marker in html:
        report.append(f"[DONE] {slug}")
        continue
    faq_present = 'class="faq-section"' in html
    if faq_present:
        anchor = '<section class="faq-section" id="faq" aria-label="Frequently Asked Questions">'
        html = html.replace(anchor, block + "\n" + anchor, 1)
    else:
        nav = '<nav class="article-nav"'
        if nav not in html:
            report.append(f"[WARN] {slug}: no nav")
            continue
        faq_html, faq_items = FAQ_ZH.get(slug, (None, None))
