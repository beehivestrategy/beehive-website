def match_div(s, start):
    """start 指向 '<div'，返回匹配的 '</div>' 结束下标"""
    depth = 0
    i = start
    while True:
        o = s.find('<div', i)
        c = s.find('</div>', i)
        if c == -1:
            raise ValueError('unbalanced')
        if o != -1 and o < c:
            depth += 1
            i = o + 4
        else:
            depth -= 1
            i = c + 6
            if depth == 0:
                return i


def rebuild_faq(s, qa):
    """把可见 FAQ 重建为 qa（4 组），返回新文本"""
    qpos = [m.start() for m in re.finditer(r'<span class="faq-number">\s*\d+\s*</span><span>', s)]
    apos = [m.start() for m in re.finditer(r'<div class="faq-answer-inner">', s)]
    if len(qpos) != len(apos):
        raise ValueError('q/a count mismatch %d/%d' % (len(qpos), len(apos)))
    n_old = len(qpos)

    # 从后往前替换，避免位置漂移
    out = s
    for idx in range(n_old - 1, -1, -1):
        q, a = qa[idx]
        # 答案
        a_start = apos[idx]
        a_open_end = out.index('>', a_start) + 1
        a_end = out.index('</div>', a_open_end)
        out = out[:a_open_end] + a + out[a_end:]
        # 问题
        q_start = qpos[idx]
        q_inner = out.index('<span>', q_start) + len('<span>')
        q_end = out.index('</span>', q_inner)
        out = out[:q_inner] + q + out[q_end:]

    # 需要补充的额外条目：克隆最后一个 faq-item
    if len(qa) > n_old:
        items = [m.start() for m in re.finditer(r'<div class="faq-item">', out)]
        if not items:
            raise ValueError('no faq-item')
        p = items[-1]
        end = match_div(out, p)
        block = out[p:end]
        # 找到插入位置（保留块后的空白/换行）
        tail_ws = ''
        k = end
        while k < len(out) and out[k] in ' \t':
            k += 1
        sep = out[end:k]
        for idx in range(n_old, len(qa)):
            q, a = qa[idx]
            nb = re.sub(r'(<span class="faq-number">)\s*\d+\s*(</span><span>).*?(</span>)',
                        lambda m: m.group(1) + str(idx + 1) + m.group(2) + q + m.group(3),
                        block, count=1, flags=re.S)
            nb = re.sub(r'(<div class="faq-answer-inner">).*?(</div>)',
                        lambda m: m.group(1) + a + m.group(2), nb, count=1, flags=re.S)
            insert_at = end
            out = out[:insert_at] + sep + nb + out[insert_at:]
            end = end + len(sep) + len(nb)
    return out


def rebuild_ld(s, qa):
    i = s.find('"@type": "FAQPage"')
    if i == -1:
        raise ValueError('no FAQPage ld')
    b = s.rfind('<script', 0, i)
    e = s.find('</script>', i)
    raw = s[s.index('>', b) + 1:e]
    d = json.loads(raw)
    d['mainEntity'] = [
        {"@type": "Question", "name": q,
         "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in qa
    ]
    new = json.dumps(d, ensure_ascii=False, indent=2)
    return s[:s.index('>', b) + 1] + '\n' + new + '\n' + s[e:]


def replace_heading(s, old, new):
    """替换 h2/h3 内部文本（不动 id/href/class/style），并同步 aria-label"""
    pat = re.compile(r'(<h([23])\b[^>]*>)\s*' + re.escape(old) + r'\s*(</h\2>)')
    n = 0
    def rep(m):
        nonlocal n
        n += 1
        open_tag = m.group(1)
        open_tag = re.sub(r'aria-label="[^"]*"', 'aria-label="%s"' % new, open_tag)
        return open_tag + new + m.group(3)
    s = pat.sub(rep, s)
    return s, n


def sync_toc(s, anchor, new):
    pat = re.compile(r'(<a[^>]*href="#' + re.escape(anchor) + r'"[^>]*>)[^<]*(</a>)')
    return pat.sub(lambda m: m.group(1) + new + m.group(2), s)


