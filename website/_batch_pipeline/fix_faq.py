TITLE_MAP = {
    "Data Quality Automation From Reactive To Proactive Part 2": "数据质量自动化：从被动到主动（二）",
    "Cfo Guide Ai Budget Allocation": "CFO 指南：AI 预算分配",
}

CJK = re.compile(r'[一-鿿]')

def txt(s):
    return re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', s)).strip()

def build_item(tpl, n, q, a):
    """tpl: raw html of one faq-item; returns new html with number n, question q, answer a"""
    out = tpl
    # number badge
    out = re.sub(r'(<span class="faq-number">)\d+(</span>)', lambda m: m.group(1) + str(n) + m.group(2), out, count=1)
    # question: variant A (span) or variant B (h3)
    if re.search(r'<span class="faq-question-text"><span class="faq-number">\d+</span><span>.*?</span></span>', out, re.S):
        out = re.sub(r'(<span class="faq-question-text"><span class="faq-number">\d+</span><span>).*?(</span></span>)',
                     lambda m: m.group(1) + q + m.group(2), out, count=1, flags=re.S)
    else:
        out = re.sub(r'(<h3 class="faq-question-text"[^>]*>).*?(</h3>)',
                     lambda m: m.group(1) + q + m.group(2), out, count=1, flags=re.S)
    # answer
    out = re.sub(r'(<div class="faq-answer-inner">).*?(</div>)',
                 lambda m: m.group(1) + a + m.group(2), out, count=1, flags=re.S)
    return out

def process(rel):
    fp = os.path.join(ROOT, rel)
    src = open(fp, encoding='utf-8').read()
    key = os.path.basename(rel)[:-5]
    qa = FAQ.get(key)
    stats = {"faq": 0, "titles": 0, "skipped": []}

    # ---------- Task A: FAQ ----------
    m = re.search(r'(<div class="faq-list">)(.*?)(\s*</div>\s*</section>)', src, re.S)
    if not m:
        stats["skipped"].append("no faq-list")
        return src, stats, False
    inner = m.group(2)
    parts = re.split(r'(?=<div class="faq-item">)', inner)
    head = parts[0]
    items = [p for p in parts[1:] if p.strip().startswith('<div class="faq-item">')]
    if len(items) != 3:
        stats["skipped"].append("faq-item count=%d" % len(items))
        return src, stats, False
    if 'undefined' not in inner:
        stats["skipped"].append("faq already valid")
        return src, stats, False

    new_items = [build_item(items[i], i + 1, qa[i][0], qa[i][1]) for i in range(3)]
    new_items.append(build_item(items[2], 4, qa[3][0], qa[3][1]))
    new_inner = head + ''.join(new_items)
    src = src[:m.start(2)] + new_inner + src[m.end(2):]
    stats["faq"] = 4

    # ---------- Task A3: JSON-LD ----------
    for lm in re.finditer(r'(<script type="application/ld\+json">)(.*?)(</script>)', src, re.S):
        try:
            data = json.loads(lm.group(2))
        except Exception:
            continue
        objs = data if isinstance(data, list) else [data]
        hit = False
        for o in objs:
            if isinstance(o, dict) and o.get("@type") == "FAQPage":
                o["mainEntity"] = [
                    {"@type": "Question", "name": q,
                     "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in qa
                ]
                hit = True
        if hit:
            newjson = json.dumps(data, ensure_ascii=False)
            src = src[:lm.start(2)] + newjson + src[lm.end(2):]
            break

    # ---------- Task B: translate English headings ----------
    def repl_h(mo):
        en = txt(mo.group(3))
        if CJK.search(en) or en not in TITLE_MAP:
            return mo.group(0)
        stats["titles"] += 1
        return mo.group(1) + mo.group(2) + '>' + TITLE_MAP[en] + '</' + mo.group(1) + '>'
    src = re.sub(r'<(h2|h3)([^>]*)>(.*?)</\1>', repl_h, src, flags=re.S)
    # recommended-card category label
    src = src.replace('<span class="recommended-card-cat">Technology</span>',
                      '<span class="recommended-card-cat">技术</span>')
    open(fp, 'w', encoding='utf-8').write(src)
    return src, stats, True

